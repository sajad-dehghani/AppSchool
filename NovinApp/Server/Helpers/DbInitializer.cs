        public static async Task SeedDefaultAdminAsync(IServiceProvider serviceProvider)
        {
            using var scope = serviceProvider.CreateScope();
            var context = scope.ServiceProvider.GetRequiredService<MyAppContext>();
            var logger = scope.ServiceProvider.GetService<ILogger<Program>>();

            try
            {
                // اطمینان از ایجاد جداول در صورت لزوم
                try
                {
                    await context.Database.EnsureCreatedAsync();
                }
                catch (Exception dbEx)
                {
                    logger?.LogWarning(dbEx, "EnsureCreated database warning (migration already applied or table exists).");
                }

                // ۱. بررسی و ایجاد کاربر پیش‌فرض ادمین
                var adminUser = await context.User.FirstOrDefaultAsync(u =>
                    u.code_meli == "admin" ||
                    u.Rool == UserRoles.SystemAdmin ||
                    u.Rool == "مدیر سیستم");

                if (adminUser == null)
                {
                    var defaultAdmin = new User
                    {
                        fname = "مدیر کل سیستم",
                        code_meli = "admin",
                        gender = "مرد",
                        mobile = "09120000000",
                        pass = PasswordHelper.HashPassword("Admin@123456"),
                        Rool = UserRoles.SystemAdmin,
                        active = true,
                        Id_School = null,
                        Id_Moshaver = null,
                        Moshaver = null
                    };

                    await context.User.AddAsync(defaultAdmin);
                    await context.SaveChangesAsync();
                    logger?.LogInformation("کاربر پیش‌فرض مدیر سیستم (SystemAdmin) با نام کاربری 'admin' با موفقیت ایجاد شد.");
                }

                // ۲. ایجاد بانک سرفصل‌ها و مباحث درسی پیش‌فرض در صورت خالی بودن
                if (!await context.StudySubjectTopics.AnyAsync())
                {
                    var defaultTopics = GetDefaultCurriculumTopics();
                    await context.StudySubjectTopics.AddRangeAsync(defaultTopics);
                    await context.SaveChangesAsync();
                    logger?.LogInformation($"تعداد {defaultTopics.Count} مبحث درسی پیش‌فرض به بانک مباحث افزوده شد.");
                }
            }
            catch (Exception ex)
            {
                logger?.LogError(ex, "خطا در مقداردهی اولیه پایگاه داده");
            }
        }

