    public Task<string> GetResponseAsync(string userInput)
    {
        // ابتدا چک می‌کنیم که آیا سوال کاربر به‌طور دقیق در لیست وجود دارد یا خیر
        if (FAQ.ContainsKey(userInput))
        {
            return Task.FromResult(FAQ[userInput]);
        }

        // اگر سوال دقیق وجود نداشت، از جستجوی شباهت استفاده می‌کنیم
        string closestQuestion = null;
        int minDistance = int.MaxValue;

        foreach (var question in FAQ.Keys)
        {
            int distance = CalculateLevenshteinDistance(userInput, question);
            if (distance < minDistance)
            {
                minDistance = distance;
                closestQuestion = question;
            }
        }

        // اگر فاصله کمتر از یک مقدار آستانه باشد (مثلاً 5)، پاسخ مرتبط را برمی‌گردانیم
        if (minDistance <= 5)
        {
            return Task.FromResult(FAQ[closestQuestion]);
        }

        return Task.FromResult("متأسفم، پاسخ این سوال را نمی‌دانم. اما می‌توانم آن را یاد بگیرم.");
    }

    private int CalculateLevenshteinDistance(string source, string target)
    {
        var n = source.Length;
        var m = target.Length;
        var dp = new int[n + 1, m + 1];

        for (var i = 0; i <= n; i++)
            dp[i, 0] = i;
        for (var j = 0; j <= m; j++)
            dp[0, j] = j;

        for (var i = 1; i <= n; i++)
        {
            for (var j = 1; j <= m; j++)
            {
                var cost = source[i - 1] == target[j - 1] ? 0 : 1;
                dp[i, j] = Math.Min(Math.Min(dp[i - 1, j] + 1, dp[i, j - 1] + 1), dp[i - 1, j - 1] + cost);
            }
        }

        return dp[n, m];
    }
