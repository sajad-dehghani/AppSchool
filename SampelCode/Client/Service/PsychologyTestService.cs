        public async Task<(bool hasTaken, PsychologyTestResult? result)> CheckStatusAsync(int userId, string testType)
        {
            try
            {
                var response = await _http.GetFromJsonAsync<StatusCheckDto>($"api/PsychologyTest/check-status/{userId}/{testType}");
                return (response?.hasTaken ?? false, response?.result);
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Error checking test status: {ex.Message}");
                return (false, null);
            }
        }

        public async Task<PsychologyTestResult?> SaveResultAsync(PsychologyTestResult model)
        {
            var res = await _http.PostAsJsonAsync("api/PsychologyTest/save", model);
            if (res.IsSuccessStatusCode)
            {
                return await res.Content.ReadFromJsonAsync<PsychologyTestResult>();
            }

            var err = await res.Content.ReadAsStringAsync();
            throw new Exception(err);
        }

