        public TestAnalysisReport CalculateReport(string testType, List<TestQuestion> questions)
        {
            return testType switch
            {
                PsychologyTestTypes.Gardner => CalculateGardnerReport(questions),
                PsychologyTestTypes.NEO => CalculateNeoReport(questions),
                PsychologyTestTypes.Cattell => CalculateCattellReport(questions),
                PsychologyTestTypes.Clifton => CalculateCliftonReport(questions),
                _ => CalculateHollandReport(questions)
            };
        }

